function generateTrend(startScore: number, endScore: number, days: number, variance: number): number[] {
  const trend: number[] = [];
  const delta = (endScore - startScore) / (days - 1);
  for (let i = 0; i < days; i++) {
    const base = startScore + delta * i;
    // Slight deterministic pseudo-random variation
    const jitter = Math.sin(i * 1.5) * variance;
    const score = Math.round(Math.max(10, Math.min(100, base + jitter)));
    trend.push(score);
  }
  trend[trend.length - 1] = endScore; // Ensure last day matches current score
  return trend;
}

function generateDroppingTrend(highScore: number, dropScore: number, days: number): number[] {
  const trend: number[] = [];
  const dropDay = Math.floor(days * 0.6); // Score drops around 24 days ago
  for (let i = 0; i < days; i++) {
    if (i < dropDay) {
      trend.push(highScore + Math.round(Math.sin(i) * 2));
    } else {
      const dropProgress = (i - dropDay) / (days - dropDay);
      const val = highScore - (highScore - dropScore) * dropProgress;
      trend.push(Math.round(Math.max(10, Math.min(100, val + Math.cos(i) * 1.5))));
    }
  }
  trend[trend.length - 1] = dropScore;
  return trend;
}

async function main() {
  console.log('Seeding VendorLens database...');

  // Check if vendors already seeded
  const existingCount = await prisma.vendor.count();
  if (existingCount > 0) {
    console.log(`Database already contains ${existingCount} vendors. Skipping re-seed.`);
    return;
  }

  for (const vData of SEED_VENDORS) {
    console.log(`Creating vendor: ${vData.name} (${vData.domain})...`);

    const vendor = await prisma.vendor.create({
      data: {
        name: vData.name,
        domain: vData.domain,
        category: vData.category,
        criticality: vData.criticality,
        declaredProducts: vData.declaredProducts,
      },
    });

    // 1. Create latest ScanResult
    const scanResult = await prisma.scanResult.create({
      data: {
        vendorId: vendor.id,
        score: vData.score,
        grade: vData.grade,
        riskTier: vData.riskTier,
        coveragePercent: vData.coverage,
        isFromCache: false,
        timestamp: new Date(),
      },
    });

    // 2. Create Findings & Remediation Items for FAILs
    for (const f of vData.findings) {
      const finding = await prisma.finding.create({
        data: {
          scanResultId: scanResult.id,
          vendorId: vendor.id,
          checkName: f.checkName,
          category: f.category,
          status: f.status,
          severity: f.severity,
          evidence: f.evidence,
          sourceUrl: f.sourceUrl,
          rawValue: f.rawValue,
          confidence: f.confidence,
          whyItMatters: f.whyItMatters,
          recommendedFix: f.recommendedFix,
          timestamp: new Date(),
        },
      });

      // If finding failed, create a prioritized remediation item
      if (f.status === 'FAIL') {
        const priorityScore = calculatePriority(f.severity, vData.criticality);
        await prisma.remediationItem.create({
          data: {
            findingId: finding.id,
            vendorId: vendor.id,
            priority: priorityScore,
            status: 'Open',
            note: `Auto-generated from scan finding: ${f.checkName}`,
          },
        });
      }
    }

    // 3. Create 60 days of synthetic score history
    const now = new Date();
    for (let dayIdx = 0; dayIdx < vData.scoreTrend.length; dayIdx++) {
      const daysAgo = vData.scoreTrend.length - 1 - dayIdx;
      const historyDate = new Date(now.getTime() - daysAgo * 24 * 60 * 60 * 1000);
      const histScore = vData.scoreTrend[dayIdx];
      const histGrade = histScore >= 90 ? 'A' : histScore >= 80 ? 'B' : histScore >= 65 ? 'C' : histScore >= 50 ? 'D' : 'F';

      await prisma.scoreHistory.create({
        data: {
          vendorId: vendor.id,
          score: histScore,
          grade: histGrade,
          coverage: vData.coverage,
          date: historyDate,
          isSynthetic: true,
        },
      });
    }

    // 4. Create CachedSnapshot for offline safety net
    await prisma.cachedSnapshot.create({
      data: {
        domain: vData.domain,
        data: JSON.stringify({
          score: vData.score,
          grade: vData.grade,
          riskTier: vData.riskTier,
          coveragePercent: vData.coverage,
          findings: vData.findings,
          capturedAt: new Date().toISOString(),
        }),
        capturedAt: new Date(),
      },
    });

    // 5. Create realistic alerts for specific vendors
    if (vData.name === 'Epic Systems') {
      await prisma.alert.create({
        data: {
          vendorId: vendor.id,
          type: 'SCORE_DROP',
          title: 'Critical Score Drop: Epic Systems (-16 pts)',
          message: 'Epic Systems security score dropped from 72 to 56 over the last 30 days due to newly published unpatched CISA KEV vulnerability.',
          severity: 'Critical',
          dismissed: false,
        },
      });

      await prisma.alert.create({
        data: {
          vendorId: vendor.id,
          type: 'KEV_MATCH',
          title: 'Active Exploited Vulnerability: CVE-2023-38606',
          message: 'CISA KEV catalog matched actively exploited authentication bypass vulnerability against Epic Systems declared infrastructure.',
          severity: 'Critical',
          dismissed: false,
        },
      });
    }

    if (vData.name === 'Mailchimp') {
      await prisma.alert.create({
        data: {
          vendorId: vendor.id,
          type: 'CERT_EXPIRY',
          title: 'Imminent TLS Certificate Expiry (22 days)',
          message: 'Primary server certificate for mailchimp.com expires in 22 days. Verify automated ACME renewal pipelines.',
          severity: 'High',
          dismissed: false,
        },
      });
    }
  }

  console.log('Seeding completed successfully!');
}

main()
  .catch((e) => {
    console.error('Error during seeding:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
